bool isSupportedCodepage(int codepage) { return tableFor(codepage) != nullptr; }

uint32_t codepageToUnicode(int codepage, uint8_t byte) {
  if (byte < 0x80) return byte;
  const uint16_t* table = tableFor(codepage);
  if (!table) return 0xFFFD;
  const uint16_t v = table[byte - 0x80];
  return v == 0 ? 0xFFFD : v;
}

void appendUtf8CodePoint(std::string& out, uint32_t cp) {
  if (cp > 0x10FFFF || (cp >= 0xD800 && cp <= 0xDFFF)) cp = 0xFFFD;
  if (cp < 0x80) {
    out.push_back(static_cast<char>(cp));
  } else if (cp < 0x800) {
    out.push_back(static_cast<char>(0xC0 | (cp >> 6)));
    out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
  } else if (cp < 0x10000) {
    out.push_back(static_cast<char>(0xE0 | (cp >> 12)));
    out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
    out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
  } else {
    out.push_back(static_cast<char>(0xF0 | (cp >> 18)));
    out.push_back(static_cast<char>(0x80 | ((cp >> 12) & 0x3F)));
    out.push_back(static_cast<char>(0x80 | ((cp >> 6) & 0x3F)));
    out.push_back(static_cast<char>(0x80 | (cp & 0x3F)));
  }
}

int codepageFromName(std::string_view name) {
  std::string n;
  for (const char c : name) {
    if (c == ' ' || c == '_') continue;
    n.push_back(c >= 'A' && c <= 'Z' ? static_cast<char>(c - 'A' + 'a') : c);
  }
  auto number = [&](size_t from) {
    int v = 0;
    for (size_t i = from; i < n.size(); ++i) {
      if (n[i] < '0' || n[i] > '9') return 0;
      v = v * 10 + (n[i] - '0');
    }
    return v;
  };
  int page = 0;
  if (n.compare(0, 8, "windows-") == 0) {
    page = number(8);
  } else if (n.compare(0, 7, "windows") == 0) {
    page = number(7);
  } else if (n.compare(0, 2, "cp") == 0) {
    page = number(2);
  } else if (n.compare(0, 3, "ibm") == 0) {
    page = number(3);
  } else if (n == "koi8-r" || n == "koi8r" || n == "koi8") {
    return 20866;
  } else if (n == "iso-8859-1" || n == "latin1" || n == "iso8859-1" || n == "l1") {
    return 1252;
  } else if (n == "iso-8859-2" || n == "latin2") {
    return 1250;
  } else if (n == "iso-8859-5") {
    return 0;
  } else if (n == "iso-8859-7") {
    return 1253;
  } else if (n == "iso-8859-9") {
    return 1254;
  } else if (n == "iso-8859-13") {
    return 1257;
  } else if (n == "cyrillic" || n == "ru") {
    return 1251;
  }
  return isSupportedCodepage(page) ? page : 0;
}

int codepageForCharset(int charset) {
  switch (charset) {
    case 0: return 1252;    // ANSI
    case 161: return 1253;  // Greek
    case 162: return 1254;  // Turkish
    case 186: return 1257;  // Baltic
    case 204: return 1251;  // Russian
    case 238: return 1250;  // Eastern European
    case 254: return 437;   // PC-437
    case 255: return 866;   // OEM (Russian installs); 437 elsewhere
    default: return 0;
  }
}

